"""Generate a controller-side Lua program that replays joint rows with ServoJ.

Why (design doc fairino-control-2.md, "Joint playback on the controller"):
MoveTPD refuses a portrait path at the wrist singularity (J5 = 0), while the
same joints streamed with ServoJ play fine. Streaming from Python depends on
the network every 8 ms; a Lua program runs the same ServoJ loop on the
controller, so a lost connection or a slow packet cannot stall the motion.

The program syntax follows the Fairino manual's Lua example
(`ServoJ({j1..j6}, {0, 0, 0, 0}, acc, vel, cmdT, filterT, gain)`, `WaitMs(ms)`).
Whether ServoJ inside Lua blocks for cmdT or queues is not documented, so the
pacing is selectable (`pace`) and measured on the robot.
"""

from __future__ import annotations

PACES = ("wait", "queue")


def resample(rows: list[list[float]], ovl: int) -> list[list[float]]:
    """The same path at `ovl` percent speed: ServoJ has no speed override, so
    a slower playback is the same path sampled at more points (linear
    interpolation between rows, the period unchanged)."""
    if not 1 <= ovl <= 100:
        raise ValueError("ovl must be 1..100")
    if ovl == 100 or len(rows) < 2:
        return [list(r) for r in rows]
    span = len(rows) - 1
    count = round(span * 100.0 / ovl) + 1
    out = []
    for k in range(count):
        x = k * span / (count - 1)
        i = min(int(x), span - 1)
        f = x - i
        out.append([a + (b - a) * f for a, b in zip(rows[i], rows[i + 1], strict=True)])
    return out


def render(
    rows: list[list[float]], period_ms: int, name: str, pace: str = "wait"
) -> str:
    """The Lua program text. `pace="wait"` adds WaitMs(period) after each
    ServoJ (as the SDK's own streaming examples sleep cmdT between calls);
    `pace="queue"` relies on the controller's ServoJ queue to pace them."""
    if pace not in PACES:
        raise ValueError(f"pace must be one of {PACES}")
    if not rows:
        raise ValueError("no rows")
    cmd_t = period_ms / 1000.0
    lines = [
        f"-- motion {name}: {len(rows)} rows, {period_ms} ms, pace {pace}.",
        "-- Generated by motionctl luaplay; do not edit.",
        "P = {",
    ]
    lines += ["{" + ", ".join(f"{v:.4f}" for v in row) + "}," for row in rows]
    lines += [
        "}",
        "E = {0, 0, 0, 0}",
        "for i = 1, #P do",
        f"    ServoJ(P[i], E, 0, 0, {cmd_t:g}, 0, 0)",
    ]
    if pace == "wait":
        lines.append(f"    WaitMs({period_ms})")
    lines += ["end", ""]
    return "\n".join(lines)
